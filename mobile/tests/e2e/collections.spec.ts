import { test, expect } from '@playwright/test';

test('like a piece, save into multiple collections, rename, remove, and persist', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('/tag/demo-1');
  await page.getByRole('button', { name: 'Like Chromatic letters', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Unlike Chromatic letters', exact: true })).toContainText('1 like');
  await page.getByRole('button', { name: 'Save piece', exact: true }).first().click();
  await page.getByLabel('Collection name', { exact: true }).fill('Zagreb favourites');
  await page.getByRole('button', { name: 'Create collection', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Zagreb favourites', exact: true })).toBeChecked();
  await page.getByLabel('Collection name', { exact: true }).fill('Lettering');
  await page.getByRole('button', { name: 'Create collection', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Lettering', exact: true })).toBeChecked();
  await page.getByRole('button', { name: 'View all saved graffiti', exact: true }).click();
  await page.getByRole('button', { name: 'Zagreb favourites (1)', exact: true }).click();
  await page.getByRole('button', { name: 'Rename collection', exact: true }).click();
  await page.getByLabel('New collection name', { exact: true }).fill('Zagreb walls');
  await page.getByRole('button', { name: 'Save collection name', exact: true }).click();
  await page.getByRole('button', { name: 'Remove from this collection', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Zagreb walls (0)', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Lettering (1)', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Open piece Chromatic letters', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Unlike Chromatic letters', exact: true })).toContainText('1 like');
  await page.getByRole('button', { name: 'Lettering (1)', exact: true }).click();
  await page.screenshot({ path: 'artifacts/collections-phone.png', fullPage: true });
  await page.getByRole('button', { name: 'Delete collection', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm delete collection', exact: true }).click();
  await expect(page.getByRole('button', { name: 'All saved (1)', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Unlike Chromatic letters', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Like Chromatic letters', exact: true })).toContainText('0 likes');
  await page.getByRole('button', { name: 'Saved · Organize', exact: true }).click();
  await page.getByRole('button', { name: 'Remove from saved and all collections', exact: true }).click();
  await expect(page.getByRole('button', { name: 'All saved (0)', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'All saved (0)', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
